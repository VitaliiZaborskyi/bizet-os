  function translateTextNode(node){
    if(!isUA()||!node||node.nodeType!==Node.TEXT_NODE)return;
    const raw=node.nodeValue||'',trim=raw.trim();if(!trim)return;
    const mapped=MAP[trim];if(!mapped)return;
    const start=raw.match(/^\s*/)?.[0]||'',end=raw.match(/\s*$/)?.[0]||'';
    node.nodeValue=start+mapped+end;
  }
  function translateElement(el){
    if(!isUA()||!el||el.nodeType!==Node.ELEMENT_NODE)return;
    const attrs=['aria-label','title','placeholder'];
    attrs.forEach(a=>{const v=el.getAttribute?.(a);if(v&&MAP[v])el.setAttribute(a,MAP[v])});
    [...el.childNodes].forEach(n=>{if(n.nodeType===Node.TEXT_NODE)translateTextNode(n)});
  }
  function walk(root=document.body){
    if(!isUA()||!root)return;
    translateElement(root);
    const w=document.createTreeWalker(root,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
    let n;while((n=w.nextNode())){if(n.nodeType===Node.TEXT_NODE)translateTextNode(n);else translateElement(n)}
    document.documentElement.lang='uk';
    document.title=document.title.replace('Рабочая модель','Робоча модель');
  }
  let raf=0;
